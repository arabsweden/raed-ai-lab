caps=[]
for i,(sc,style,pos,ws) in enumerate(C):
    frm = st[ws[0][1]]
    words=[]
    for t,idx in ws:
        emph = t.endswith("!")
        t = t.rstrip("!")
        s = st[idx] if idx>=0 else words[-1]["s"]
        words.append({"t":t,"s":s,"emph":emph,"latin":bool(re.match(r"^[A-Za-zÅÄÖåäö]",t)),"num":bool(re.match(r"^\d",t)),"punct":idx<0})
