import {readFileSync, writeFileSync} from "fs";
import {feature} from "topojson-client";
import {geoPath, geoConicConformal} from "d3-geo";
const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-10m.json","utf8"));
const fc = feature(topo, topo.objects.countries);
const se = fc.features.find(f => f.id === "752");
const W=520,H=1100;
const proj = geoConicConformal().rotate([-16,0]).parallels([56,68]).fitSize([W,H], se);
const p = geoPath(proj).digits(1);
const d = p(se);
const pt = (lon,lat)=>proj([lon,lat]).map(v=>Math.round(v*10)/10);
const out = `// Generated by gen-map.mjs from world-atlas (Natural Earth 10m). Do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const SWEDEN_PATH = ${JSON.stringify(d)};
export const TRANAS_XY: [number, number] = ${JSON.stringify(pt(14.976,58.035))};
export const STOCKHOLM_XY: [number, number] = ${JSON.stringify(pt(18.07,59.33))};
`;
writeFileSync("src/sweden.ts", out);
